// Utility to generate dynamic ISO dates relative to today
const now = new Date();
const formatDate = (date) => date.toISOString().split("T")[0];
const addDays = (days) => {
  const d = new Date(now);
  d.setDate(d.getDate() + days);
  return formatDate(d);
};
const subDays = (days) => {
  const d = new Date(now);
  d.setDate(d.getDate() - days);
  return formatDate(d);
};

